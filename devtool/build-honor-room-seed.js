import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(root, "history", "club-career-data.json");
const outputPath = path.join(root, "versus", "honor-room-seed.js");

const honorsByOwner = Object.freeze({
  "P-A927135074":{ league:["S2","S6","S8","S9","S10","S12"], cup:["S1","S6","S7","S8","S9"], worldCup:[] },
  "P-C0ACCAAD1C":{ league:["S4前"], cup:["S12"], worldCup:[] },
  "P-5CF850B13B":{ league:["S4前","S3","S4","S7"], cup:["S3","S4"], worldCup:[] },
  "P-F17F668064":{ league:["S5"], cup:["S5","S10"], worldCup:["世界杯 I"] },
  "P-A9C66353D3":{ league:["S13"], cup:["S13"], worldCup:[] },
  "P-23D50182AD":{ league:[], cup:[], worldCup:[] },
  "P-269ABD614F":{ league:["S11"], cup:[], worldCup:[] },
  "P-A3FCAA6528":{ league:[], cup:[], worldCup:["世界杯 II"] },
  "P-F162C8A606":{ league:["S4前","S1"], cup:["S11"], worldCup:[] },
});

const ballonDorByOwner = Object.freeze({
  "P-F17F668064":[{ season:"历史金球奖", playerId:"s4-dlc2-20260803-071", playerName:"德尔·皮耶罗" }],
  "P-A927135074":[{ season:"历史金球奖", playerId:"legend-cristiano-ronaldo", playerName:"C罗" }],
  "P-A9C66353D3":[{ season:"历史金球奖", playerId:"s4-fc26-231443", playerName:"登贝莱" }],
});

const source = JSON.parse(fs.readFileSync(sourcePath, "utf8"));
const clubs = Object.fromEntries(source.clubs.map((club) => [club.ownerId, {
  ownerId:club.ownerId,
  ownerName:club.ownerName,
  teamId:club.currentTeamId,
  teamName:club.currentTeamName,
  honors:honorsByOwner[club.ownerId] ?? { league:[], cup:[], worldCup:[] },
  ballonDor:ballonDorByOwner[club.ownerId] ?? [],
  players:Object.fromEntries(club.players.map((player) => [player.playerId, {
    playerId:player.playerId,
    playerName:player.playerName,
    appearances:Number(player.total.appearances ?? 0),
    goals:Number(player.total.goals ?? 0),
    assists:Number(player.total.assists ?? 0),
    ratingTotal:Number(player.total.ratingTotal ?? 0),
  }])),
}]));

const seed = {
  schemaVersion:1,
  sourceRevision:source.revision,
  updatedAt:Date.parse(source.generatedAt),
  nextSeasonNumber:14,
  processedSeasonIds:source.diagnostics.map((entry) => entry.seasonId),
  clubs,
};

fs.writeFileSync(outputPath, `// Generated by devtool/build-honor-room-seed.js.\nexport const HONOR_ROOM_SEED = Object.freeze(${JSON.stringify(seed, null, 2)});\n`);
console.log(`Wrote ${path.relative(root, outputPath)} (${Object.values(clubs).reduce((sum, club) => sum + Object.keys(club.players).length, 0)} player records)`);
