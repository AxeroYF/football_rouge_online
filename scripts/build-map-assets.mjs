import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { isEuropeanFeature, isSouthAmericanFeature } from '../client/map/campaign-map-geometry.js';

const root = new URL('../', import.meta.url);
const check = process.argv.includes('--check');
const source = JSON.parse(await readFile(new URL('assets/data/natural-earth-countries-50m.geojson', root), 'utf8'));
// Keep the original coordinates and properties; omit only countries outside the campaign.
const countries = JSON.stringify({ ...source, features: source.features.filter(f => isEuropeanFeature(f) || isSouthAmericanFeature(f)) });
const countriesPath = 'assets/data/campaign-countries.geojson';
const paths = [countriesPath, 'assets/data/europe-cities.json', 'assets/data/south-america-cities.json',
  'assets/data/europe-clubs.json', 'assets/data/campaign-territories.geojson', 'assets/data/territory-index.json',
  'assets/data/campaign-boundaries.json', 'assets/data/campaign-coastlines.json', 'assets/data/territory-resources.json', 'shared/config/map-relief-regions.json',
  'assets/data/map-nature.json', 'assets/data/map-environment.json',
  ...['europe', 'south-america', 'svalbard'].flatMap(region => ['json', 'bin'].map(ext => `assets/map-relief/relief-mesh/${region}.${ext}`))];
const hashes = {};
for (const file of paths) {
  const bytes = file === countriesPath ? Buffer.from(countries) : await readFile(new URL(file, root));
  hashes[file] = createHash('sha256').update(bytes).digest('hex');
}
const manifest = `// Generated by scripts/build-map-assets.mjs; rerun after changing a map source.\nexport const MAP_ASSET_HASHES = Object.freeze(${JSON.stringify(hashes, null, 2)});\n\nexport function mapAssetUrl(path) {\n  const relative = path.replace(/^\\.\\//, '');\n  const hash = MAP_ASSET_HASHES[relative];\n  if (!hash) throw new Error('Unknown map asset: ' + path);\n  return './' + relative + '?v=sha256-' + hash;\n}\n`;
for (const [file, text] of [[countriesPath, countries], ['shared/config/map-assets.mjs', manifest]]) {
  if (check) {
    if (await readFile(new URL(file, root), 'utf8') !== text) throw new Error(file + ' is stale; run npm run build:map-assets');
  } else await writeFile(new URL(file, root), text);
}
console.log(`${check ? 'Verified' : 'Built'} ${paths.length} content-versioned map assets; ${source.features.length} → ${JSON.parse(countries).features.length} campaign countries.`);
