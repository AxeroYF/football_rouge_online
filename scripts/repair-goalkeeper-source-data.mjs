// Backfill detailed EA fields without rerunning localization/name edits.
// Idempotent; defaults to preview. Explicit --apply writes the generated inputs.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {goalkeeperOutfieldFromReference} from '../shared/football/player-source-attributes.js';
import {S4_PLAYER_DATABASE} from '../versus/player-pool-s4-generated.js';
const root=fileURLToPath(new URL('../',import.meta.url));
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
function csv(text){
  const rows=[];let row=[],cell='',quoted=false;
  for(let i=0;i<text.length;i++){const c=text[i];if(quoted&&c==='"'&&text[i+1]==='"'){cell+='"';i++;continue;}if(c==='"'){quoted=!quoted;continue;}if(!quoted&&c===','){row.push(cell);cell='';continue;}if(!quoted&&c==='\n'){row.push(cell.replace(/\r$/,''));rows.push(row);row=[];cell='';continue;}cell+=c;}
  if(cell||row.length){row.push(cell.replace(/\r$/,''));rows.push(row);}const headers=rows.shift();return rows.filter(r=>r.length>1).map(r=>Object.fromEntries(headers.map((h,i)=>[h,r[i]])));
}
const ea=new Map(csv(read('data/sources/eafc26-player-database-20251124/EAFC26-Men.csv')).map(p=>[p.ID,p]));
const changes=[];
function repair(p,file){
  if(p.role!=='GK')return;
  const id=String(p.sourceId??'').match(/^\d+$/)?.[0]??p.sourceUrl?.match(/player-ratings\/[^/]+\/(\d+)/)?.[1],row=ea.get(id);
  if(!row)return;
  const detail={sprintSpeed:Number(row['Sprint Speed']),ballDribbling:Number(row.Dribbling)};
  const mapped=goalkeeperOutfieldFromReference(detail);
  for(const value of [p.eafcReferenceAttributes,p.referenceAttributes,p.attributes])if(value&&Object.hasOwn(value,'sprintSpeed'))value.ballDribbling=detail.ballDribbling;
  if(!Object.hasOwn(p.attributes,'firstTouch')||p.goalkeeperMappingVersion===1)return;
  const offset=p.attributes.acceleration-Number(row.Acceleration),clamp=n=>Math.max(1,Math.min(99,Math.round(n)));
  if(p.attributes.pace!==clamp(Number(row.PAC)+offset)||p.attributes.dribbling!==clamp(Number(row.DRI)+offset))return;
  const before={pace:p.attributes.pace,dribbling:p.attributes.dribbling};
  p.attributes.pace=clamp(mapped.pace+offset);p.attributes.dribbling=clamp(mapped.dribbling+offset);p.goalkeeperMappingVersion=1;
  changes.push({file,id:p.id,name:p.displayNameZh,before,after:{pace:p.attributes.pace,dribbling:p.attributes.dribbling},sourceColumns:['Sprint Speed','Dribbling']});
}
const writes=[];
for(const file of ['data/s4-player-candidates-500.json','data/s4-player-pool-s4.json']){
  const payload=JSON.parse(read(file));payload.players.forEach(p=>repair(p,file));writes.push([file,JSON.stringify(payload,null,2)+'\n']);
}
const generated=structuredClone(S4_PLAYER_DATABASE);generated.forEach(p=>repair(p,'versus/player-pool-s4-generated.js'));
writes.push(['versus/player-pool-s4-generated.js','// Generated by devtool/apply-s4-player-localization.js.\nexport const S4_PLAYER_DATABASE = Object.freeze('+JSON.stringify(generated,null,2)+');\n']);
if(process.argv.includes('--apply'))for(const [file,value]of writes)if(read(file)!==value)fs.writeFileSync(path.join(root,file),value);
fs.mkdirSync(path.join(root,'outputs/player-data-fix'),{recursive:true});
const reportPath=path.join(root,'outputs/player-data-fix/goalkeeper-source-changes.json');
if(changes.length||!fs.existsSync(reportPath))fs.writeFileSync(reportPath,JSON.stringify(changes,null,2));
console.log(JSON.stringify({applied:process.argv.includes('--apply'),changes:changes.length,players:generated.filter(p=>p.goalkeeperMappingVersion===1).length}));
